-- Intermediate Queries (Business analysis)

-- Which contract type has the highest number of churned customers?

SELECT
    Contract,
    COUNT(*) AS Churned_Customers
FROM customer_churn
WHERE Churn = 'Yes'
GROUP BY Contract
ORDER BY Churned_Customers DESC; 

-- Which payment method is used the most by churned customers?

SELECT
    PaymentMethod,
    COUNT(*) AS Churned_Customers
FROM customer_churn
WHERE Churn = 'Yes'
GROUP BY PaymentMethod
ORDER BY Churned_Customers DESC;

-- What is the average monthly charge for churned vs non-churned customers?

SELECT
    Churn,
    ROUND(AVG(MonthlyCharges), 2) AS Avg_Monthly_Charges
FROM customer_churn
GROUP BY Churn;

-- How much total revenue has been generated by churned and retained customers?

SELECT
    Churn,
    ROUND(SUM(TotalCharges), 2) AS Total_Revenue
FROM customer_churn
GROUP BY Churn;    #Since TotalCharges now contains NULL instead of blanks, SUM() will automatically ignore those NULL values.

-- Which internet service has the highest churn rate?

SELECT
    InternetService,
    COUNT(*) AS Churned_Customers
FROM customer_churn
WHERE Churn = 'Yes'
GROUP BY InternetService
ORDER BY Churned_Customers DESC;

-- Advance Queries (Advanced analytics)
-- Customer Segmentation by Tenure
-- Which tenure segment has the highest number of churned customers?

SELECT
    CASE
        WHEN tenure <= 12 THEN '0-12 Months'
        WHEN tenure <= 24 THEN '13-24 Months'
        WHEN tenure <= 48 THEN '25-48 Months'
        ELSE '49+ Months'
    END AS Tenure_Segment,
    COUNT(*) AS Churned_Customers
FROM customer_churn
WHERE Churn = 'Yes'
GROUP BY Tenure_Segment
ORDER BY Churned_Customers DESC;

-- Rank Customers by Total Charges

-- Who are the top 10 customers based on total charges?

SELECT
    customerID,
    TotalCharges,
    RANK() OVER (ORDER BY TotalCharges DESC) AS Customer_Rank
FROM customer_churn
WHERE TotalCharges IS NOT NULL
LIMIT 10;

-- Monthly Charges Compared to Overall Average

-- Which customers pay more than the average monthly charge?

SELECT
    customerID,
    MonthlyCharges
FROM customer_churn
WHERE MonthlyCharges >
(
    SELECT AVG(MonthlyCharges)
    FROM customer_churn
)
ORDER BY MonthlyCharges DESC;

-- High-Risk Customer List using CTE

-- Identify high-value customers who have churned.

WITH High_Value_Customers AS
(
    SELECT
        customerID,
        Contract,
        MonthlyCharges,
        TotalCharges
    FROM customer_churn
    WHERE Churn = 'Yes'
      AND MonthlyCharges > 70
)

SELECT *
FROM High_Value_Customers
ORDER BY TotalCharges DESC;

-- Rank Contract Types by Revenue
-- Which contract type generates the highest total revenue?

SELECT
    Contract,
    ROUND(SUM(TotalCharges),2) AS Total_Revenue,
    DENSE_RANK() OVER (ORDER BY SUM(TotalCharges) DESC) AS Revenue_Rank
FROM customer_churn
GROUP BY Contract;











